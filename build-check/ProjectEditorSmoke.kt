import ru.mebel3d.app.core.*
fun main() {
 val a = RoomModel(id="room-a", name="Кухня")
 val b = RoomModel(id="room-b", name="Спальня")
 var p = ProjectModel("p", "Дом", listOf(a), listOf(FurnitureItem("f1", "Шкаф", Size3Mm(1000,600,2200), Vec3Mm(1000,1000), roomId="room-a")))
 p = ProjectEditor.addRoom(p,b)
 check(p.activeRoomId == "room-b")
 check(ProjectEditor.furnitureInActiveRoom(p).isEmpty())
 p = ProjectEditor.activateRoom(p,"room-a")
 check(ProjectEditor.furnitureInActiveRoom(p).single().id == "f1")
 p = ProjectEditor.duplicateRoom(p,"room-a","room-c","Кухня 2")
 check(p.furniture.any { it.id == "room-c-f1" && it.roomId == "room-c" })
 p = ProjectEditor.removeRoom(p,"room-a")
 check(p.furniture.none { it.roomId == "room-a" })
 check(p.rooms.any { it.id == p.activeRoomId })
 val history = ProjectHistory(p)
 val changed = ProjectEditor.renameRoom(p,"room-c","Вторая кухня")
 history.commit(changed)
 check(history.undo().rooms.first { it.id == "room-c" }.name == "Кухня 2")
 check(history.redo().rooms.first { it.id == "room-c" }.name == "Вторая кухня")
 val roundRoom = RoomModel(id="round-room", widthMm=5000, depthMm=4000, heightMm=2700)
 val roundItem = FurnitureItem("round-table", "Круглый стол", Size3Mm(800,800,750), Vec3Mm(2000,2000), roomId="round-room", footprintShape=FurnitureFootprintShape.CIRCLE)
 val roundProject = ProjectModel("round-project", "Тест круга", listOf(roundRoom), listOf(roundItem), activeRoomId="round-room")
 val resizedRound = ProjectEditor.resizeFurniture(roundProject, "round-table", 1100, 900, 760).furniture.single()
 check(resizedRound.size.width == 1100 && resizedRound.size.depth == 1100 && resizedRound.size.height == 760)
 check(resizedRound.footprintShape == FurnitureFootprintShape.CIRCLE)
 val resizedRectangle = ProjectEditor.resizeFurniture(roundProject.copy(furniture=listOf(roundItem.copy(id="rect", footprintShape=FurnitureFootprintShape.RECTANGLE))), "rect", 1100, 900, 760).furniture.single()
 check(resizedRectangle.size.width == 1100 && resizedRectangle.size.depth == 900)
 println("ProjectEditor smoke: 11 assertions passed")
}
