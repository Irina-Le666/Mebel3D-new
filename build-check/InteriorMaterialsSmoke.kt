import ru.mebel3d.app.core.*

fun main() {
    check(InteriorMaterialLibrary.all.size >= 20)
    check(InteriorMaterialLibrary.all.map { it.id }.distinct().size == InteriorMaterialLibrary.all.size)
    check(InteriorMaterialLibrary.forUse(SurfaceUse.UPHOLSTERY).any { it.family == SurfaceFamily.TEXTILE })
    check(InteriorMaterialLibrary.forUse(SurfaceUse.COUNTERTOP).any { it.family == SurfaceFamily.STONE })
    check(InteriorMaterialLibrary.validate("fabric-linen", SurfaceUse.UPHOLSTERY) == null)
    check(InteriorMaterialLibrary.validate("fabric-linen", SurfaceUse.FLOOR) != null)
    check(InteriorMaterialLibrary.validate("missing", SurfaceUse.FURNITURE) != null)
    val room = RoomModel(id = "r")
    val item = FurnitureItem("f", "Диван", Size3Mm(1800, 900, 800), Vec3Mm(1500, 1200), roomId = "r")
    val part = FurniturePart("p", "Фасад", Size3Mm(600, 18, 700), Vec3Mm(0,0,0))
    val assembly = FurnitureAssembly("a", "Шкаф", Vec3Mm(0,0,0), listOf(part))
    val project = ProjectModel("pr", "Тест", listOf(room), listOf(item), listOf(assembly))
    val changedFurniture = ProjectEditor.applyFurnitureMaterial(project, "f", "fabric-linen")
    check(changedFurniture.furniture.single().materialId == "fabric-linen")
    check(changedFurniture.furniture.single().colorArgb == InteriorMaterialLibrary.find("fabric-linen")!!.argb)
    val changedPart = ProjectEditor.applyAssemblyPartMaterial(project, "a", "p", "metal-black")
    check(changedPart.assemblies.single().parts.single().materialId == "metal-black")
    check(project.assemblies.single().parts.single().materialId == "wood-oak")
    val changedWall = ProjectEditor.applyRoomSurface(project, "r", SurfaceUse.WALL, "solid-green")
    check(changedWall.rooms.single().wallColorArgb == InteriorMaterialLibrary.find("solid-green")!!.argb)
    check(changedWall.rooms.single().floorColorArgb == room.floorColorArgb)
    val changedFloor = ProjectEditor.applyRoomSurface(project, "r", SurfaceUse.FLOOR, "tile-sand")
    check(changedFloor.rooms.single().floorColorArgb == InteriorMaterialLibrary.find("tile-sand")!!.argb)
    check(runCatching { ProjectEditor.applyRoomSurface(project, "r", SurfaceUse.WALL, "fabric-linen") }.isFailure)
    check(runCatching { ProjectEditor.applyFurnitureMaterial(project, "f", "tile-sand") }.isFailure)
    check(runCatching { ProjectEditor.applyAssemblyPartMaterial(project, "bad", "p", "metal-black") }.isFailure)
    println("InteriorMaterialsSmoke: 15 checks passed")
}
